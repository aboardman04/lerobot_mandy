#!/usr/bin/env python3
"""
convert_joints_to_ee.py

Copy a LeRobot v3.0 dataset while converting `action` and `observation.state`
from joint-angle space to end-effector (EE) Cartesian pose space, using
LeRobot's own forward-kinematics processor for the SO-100 / SO-101
"so_follower" arm family (RobotKinematics + ForwardKinematicsJointsToEE).

What it does
------------
1. Downloads the source dataset repo from the Hub (or uses a local root you
   already have).
2. Copies the whole dataset folder to a new location. Videos are NOT touched
   -- only the tabular joint data changes, so no re-encoding is needed.
3. For every row in every `data/**/*.parquet` file, runs the arm joint
   angles for both `action` and `observation.state` through LeRobot's
   ForwardKinematicsJointsToEE step to get the EE pose, and replaces those
   columns.
4. Updates `meta/info.json` so the `action` / `observation.state` feature
   entries describe the new 7-dim EE vector instead of the old 6-dim joint
   vector.
5. Tells you the one LeRobot CLI command to run afterwards to recompute
   dataset statistics (needed for training normalization), since stats
   depend on the actual values and are best regenerated by LeRobot itself
   rather than hand-rolled here.

Before running
--------------
- `pip install lerobot huggingface_hub pandas pyarrow` (in your lerobot env).
- Download the SO-ARM kinematics URDF (this is NOT bundled with every
  lerobot version) from:
      https://github.com/TheRobotStudio/SO-ARM100/tree/main/Simulation/SO101
  (use the SO101 folder if your arm/calibration is SO-101, or the SO100
  folder if it's SO-100) and point URDF_PATH at the .urdf file.
- Edit the CONFIGURATION block below: repo ids, URDF path, output location.

Notes on this specific dataset
-------------------------------
- Your dataset's gripper values are already a small normalized range
  (e.g. ~0.55), not 0-100. That's fine -- forward kinematics never touches
  the gripper value, it's just carried through unchanged as `gripper.pos`
  in the new EE vector.
- The joint order in your `meta/info.json` is:
  shoulder_pan, shoulder_lift, elbow_flex, wrist_flex, wrist_roll, gripper
  which is what JOINT_NAMES / GRIPPER_NAME below assume.
"""

import json
import shutil
from pathlib import Path

import numpy as np
import pandas as pd
from huggingface_hub import snapshot_download

from lerobot.model.kinematics import RobotKinematics
from lerobot.processor import RobotProcessorPipeline
from lerobot.processor.converters import (
    robot_action_to_transition,
    transition_to_robot_action,
)
from lerobot.robots.so_follower.robot_kinematic_processor import (
    ForwardKinematicsJointsToEE,
)

# --------------------------------------------------------------------------
# 1. CONFIGURATION -- edit these before running
# --------------------------------------------------------------------------

# The dataset you linked.
SOURCE_REPO_ID = "aboardman/my_giant_combined_dataset2-5-6-8-9-10-rep"

# Name for the new, EE-space version. Only matters if you push it back to
# the Hub at the end.
OUTPUT_REPO_ID = "aboardman/my_giant_combined_dataset2-5-6-8-9-10-rep-ee"

# Local working folders.
WORK_DIR = Path("./lerobot_ee_conversion")
SOURCE_DIR = WORK_DIR / "source"
OUTPUT_DIR = WORK_DIR / "output"

# If you've already got the dataset cached locally (e.g. via a prior
# LeRobotDataset() call), point this at that folder instead of re-downloading.
USE_EXISTING_SOURCE_DIR = None  # e.g. Path.home() / ".cache/huggingface/lerobot/aboardman/..."

# Path to the SO-ARM kinematics URDF (see docstring above for where to get it)
# and the name of the frame at the tip of the gripper in that URDF.
URDF_PATH = "/home/aboardman/lerobot/SO101/so101_new_calib.urdf"
TARGET_FRAME_NAME = "gripper_frame_link"

# Joint order exactly as it appears in this dataset's action/observation.state
# vectors (from meta/info.json), split into "arm" joints (used by FK) and the
# gripper (passed through untouched).
JOINT_NAMES = ["shoulder_pan", "shoulder_lift", "elbow_flex", "wrist_flex", "wrist_roll"]
GRIPPER_NAME = "gripper"
ALL_MOTOR_NAMES = JOINT_NAMES + [GRIPPER_NAME]

# New feature names/order that will replace the old joint names in the
# converted dataset's action / observation.state vectors.
EE_NAMES = ["x", "y", "z", "wx", "wy", "wz", "gripper.pos"]

PUSH_TO_HUB = False  # set True to upload the converted dataset when finished

# --------------------------------------------------------------------------


def build_fk_pipeline() -> RobotProcessorPipeline:
    """Build LeRobot's forward-kinematics processor for this arm."""
    kinematics = RobotKinematics(
        urdf_path=URDF_PATH,
        target_frame_name=TARGET_FRAME_NAME,
        joint_names=JOINT_NAMES,
    )
    return RobotProcessorPipeline(
        steps=[ForwardKinematicsJointsToEE(kinematics=kinematics, motor_names=JOINT_NAMES)],
        to_transition=robot_action_to_transition,
        to_output=transition_to_robot_action,
    )


def joints_to_ee(pipeline: RobotProcessorPipeline, values) -> np.ndarray:
    """[shoulder_pan, shoulder_lift, elbow_flex, wrist_flex, wrist_roll, gripper]
    -> [x, y, z, wx, wy, wz, gripper.pos]"""
    joint_dict = {f"{name}.pos": float(v) for name, v in zip(ALL_MOTOR_NAMES, values)}
    ee_dict = pipeline(joint_dict)
    return np.array(
        [
            ee_dict["ee.x"],
            ee_dict["ee.y"],
            ee_dict["ee.z"],
            ee_dict["ee.wx"],
            ee_dict["ee.wy"],
            ee_dict["ee.wz"],
            ee_dict["ee.gripper_pos"],
        ],
        dtype=np.float32,
    )


def convert_column(pipeline: RobotProcessorPipeline, column: pd.Series) -> pd.Series:
    return column.apply(lambda vals: joints_to_ee(pipeline, vals))


def update_info_json(info_path: Path) -> None:
    with open(info_path) as f:
        info = json.load(f)
    for key in ("action", "observation.state"):
        info["features"][key]["names"] = list(EE_NAMES)
        info["features"][key]["shape"] = [len(EE_NAMES)]
    with open(info_path, "w") as f:
        json.dump(info, f, indent=4)


def main() -> None:
    WORK_DIR.mkdir(parents=True, exist_ok=True)

    if USE_EXISTING_SOURCE_DIR is not None:
        source_dir = Path(USE_EXISTING_SOURCE_DIR)
    else:
        print(f"Downloading source dataset {SOURCE_REPO_ID} ...")
        SOURCE_DIR.mkdir(parents=True, exist_ok=True)
        snapshot_download(repo_id=SOURCE_REPO_ID, repo_type="dataset", local_dir=SOURCE_DIR)
        source_dir = SOURCE_DIR

    print(f"Copying dataset to {OUTPUT_DIR} (videos are copied as-is, not re-encoded) ...")
    if OUTPUT_DIR.exists():
        shutil.rmtree(OUTPUT_DIR)
    shutil.copytree(source_dir, OUTPUT_DIR)

    print("Building forward-kinematics pipeline from the URDF ...")
    pipeline = build_fk_pipeline()

    data_files = sorted((OUTPUT_DIR / "data").rglob("*.parquet"))
    print(f"Found {len(data_files)} parquet file(s) to convert.")

    for i, path in enumerate(data_files, 1):
        print(f"  [{i}/{len(data_files)}] converting {path.relative_to(OUTPUT_DIR)} ...")
        df = pd.read_parquet(path)
        df["action"] = convert_column(pipeline, df["action"])
        df["observation.state"] = convert_column(pipeline, df["observation.state"])
        df.to_parquet(path, index=False)

    print("Updating meta/info.json feature schema (action / observation.state) ...")
    update_info_json(OUTPUT_DIR / "meta" / "info.json")

    print("\nParquet conversion done.")
    print(
        "Next, recompute dataset stats with LeRobot's own tool -- required for "
        "training/normalization to work correctly on the new EE values:\n\n"
        f"    lerobot-edit-dataset \\\n"
        f"        --repo_id {OUTPUT_REPO_ID} \\\n"
        f"        --root {OUTPUT_DIR} \\\n"
        f"        --operation.type recompute_stats\n"
    )

    if PUSH_TO_HUB:
        from huggingface_hub import HfApi

        print(f"Pushing converted dataset to {OUTPUT_REPO_ID} ...")
        api = HfApi()
        api.create_repo(repo_id=OUTPUT_REPO_ID, repo_type="dataset", exist_ok=True)
        api.upload_folder(repo_id=OUTPUT_REPO_ID, repo_type="dataset", folder_path=str(OUTPUT_DIR))

    print(f"\nDone. Converted dataset is at: {OUTPUT_DIR.resolve()}")


if __name__ == "__main__":
    main()